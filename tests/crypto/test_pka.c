/* ExpMod with the public exponent e (the "Encrypt"/"Verify" direction)
 * followed by ExpMod with the private exponent d (the "Decrypt"/"Sign"
 * direction) should recover the original input. */
static void Test_Pka_ModExp_RoundTrip(void)
{
    uint8_t ct[128];
    uint8_t recovered[128];

    WHAL_ASSERT_EQ(whal_Pka_ModExp(testInput, sizeof(testInput),
                                      rsaE, sizeof(rsaE),
                                      rsaN, sizeof(rsaN),
                                      ct, sizeof(ct)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_EQ(whal_Pka_ModExp(ct, sizeof(ct),
                                      rsaD, sizeof(rsaD),
                                      rsaN, sizeof(rsaN),
                                      recovered, sizeof(recovered)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(recovered, testInput, sizeof(testInput));
}

/* ExpMod with public exponent followed by RsaCrtExp with the CRT params
 * should also recover the original input. Validates the CRT path. */
static void Test_Pka_RsaCrtExp_RoundTrip(void)
{
    uint8_t ct[128];
    uint8_t recovered[128];

    WHAL_ASSERT_EQ(whal_Pka_ModExp(testInput, sizeof(testInput),
                                      rsaE, sizeof(rsaE),
                                      rsaN, sizeof(rsaN),
                                      ct, sizeof(ct)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_EQ(whal_Pka_RsaCrtExp(ct, sizeof(ct),
                                         rsaDP, sizeof(rsaDP),
                                         rsaDQ, sizeof(rsaDQ),
                                         rsaQInv, sizeof(rsaQInv),
                                         rsaP, sizeof(rsaP),
                                         rsaQ, sizeof(rsaQ),
                                         recovered, sizeof(recovered)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(recovered, testInput, sizeof(testInput));
}

/* Plain ExpMod-with-d and RsaCrtExp must produce identical results for
 * the same ciphertext. Catches CRT-vs-plain divergence. */
static void Test_Pka_CrtMatchesPlain(void)
{
    uint8_t ct[128];
    uint8_t plainOut[128];
    uint8_t crtOut[128];

    WHAL_ASSERT_EQ(whal_Pka_ModExp(testInput, sizeof(testInput),
                                      rsaE, sizeof(rsaE),
                                      rsaN, sizeof(rsaN),
                                      ct, sizeof(ct)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_EQ(whal_Pka_ModExp(ct, sizeof(ct),
                                      rsaD, sizeof(rsaD),
                                      rsaN, sizeof(rsaN),
                                      plainOut, sizeof(plainOut)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_EQ(whal_Pka_RsaCrtExp(ct, sizeof(ct),
                                         rsaDP, sizeof(rsaDP),
                                         rsaDQ, sizeof(rsaDQ),
                                         rsaQInv, sizeof(rsaQInv),
                                         rsaP, sizeof(rsaP),
                                         rsaQ, sizeof(rsaQ),
                                         crtOut, sizeof(crtOut)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(plainOut, testInput, sizeof(testInput));
    WHAL_ASSERT_MEM_EQ(crtOut, testInput, sizeof(testInput));
}

